/** 按日期轮换的每日一答:对日期字符串做简单 hash,同一天稳定不变 */
export function qaOfDate(date: string): QaEntry {
  let h = 0;
  for (let i = 0; i < date.length; i++) {
    h = (h * 31 + date.charCodeAt(i)) % 100000;
  }
  return QA_BANK[h % QA_BANK.length];
}
